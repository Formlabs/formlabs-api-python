def _provided(**kwargs: Any) -> dict[str, Any]:
    return {k: v for k, v in kwargs.items() if not isinstance(v, Unset)}


def _select_body(
    op_name: str,
    provided: dict[str, Any],
    variants: tuple[tuple[type, tuple[str, ...], tuple[str, ...]], ...],
) -> Any:
    given = set(provided)
    matches = [
        cls
        for cls, required, allowed in variants
        if set(required) <= given <= set(allowed)
    ]
    if len(matches) != 1:
        options = "; ".join(
            f"{cls.__name__} (required: {', '.join(required) or 'none'}; "
            f"allowed: {', '.join(allowed)})"
            for cls, required, allowed in variants
        )
        raise TypeError(
            f"{op_name}() arguments match "
            f"{'no' if not matches else 'more than one'} body variant — "
            f"provide arguments for exactly one of: {options}"
        )
    return matches[0](**provided)


